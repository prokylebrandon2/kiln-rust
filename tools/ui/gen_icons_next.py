def legacy_paths():
    text = (ROOT / "ui/ui/icons.slint").read_text(encoding="utf-8").replace("\r", "")
    return dict(re.findall(r'name == "([a-z_0-9]+)" \? "([^"]*)"', text))


def main():
    legacy = legacy_paths()
    rows = {}
    for new, old in FROM_LEGACY.items():
        if old not in legacy:
            raise SystemExit(f"icon '{old}' is not in ui/ui/icons.slint")
        rows[new] = legacy[old]
    rows.update(AUTHORED)
    out = [
        "// GENERATED by tools/ui/gen_icons_next.py. Do not edit by hand.",
        "// Every icon is one filled path on a 24x24 viewport (draw it with `Icon`).",
        "",
        "export global Icons {",
    ]
    for name in sorted(rows):
        out.append(f'    out property <string> {name}: "{rows[name]}";')
    out.append("}")
    (ROOT / "ui-next/ui/icons.slint").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote ui-next/ui/icons.slint ({len(rows)} icons)")


if __name__ == "__main__":
    main()
