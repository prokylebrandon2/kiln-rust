#!/usr/bin/env python3
"""Generate ui/ui/icons.slint from app/src/main/res/drawable/ic_*.xml.

Every icon is a single filled vector path on a 24x24 viewport (the launcher foreground and the
Kiln mark are multi-path and live in ui/ui/mark.slint instead). Run from the repository root:

    python3 tools/gen_icons.py
"""
import glob
import os
import re
import xml.etree.ElementTree as ET

ANDROID = "{http://schemas.android.com/apk/res/android}"
SRC = "app/src/main/res/drawable"
OUT = "ui/ui/icons.slint"
SKIP = {"ic_kiln", "ic_launcher_fg", "ic_launcher_icon"}

icons = []
for path in sorted(glob.glob(os.path.join(SRC, "ic_*.xml"))):
    name = os.path.basename(path)[:-4]
    if name in SKIP:
        continue
    root = ET.parse(path).getroot()
    vw = float(root.get(ANDROID + "viewportWidth"))
    vh = float(root.get(ANDROID + "viewportHeight"))
    paths = root.findall("path")
    assert (vw, vh) == (24.0, 24.0) and len(paths) == 1, name
    p = paths[0]
    data = re.sub(r"\s+", " ", p.get(ANDROID + "pathData").strip())
    even = p.get(ANDROID + "fillType") == "evenOdd"
    icons.append((name[3:], data, even))

lines = []
lines.append("// GENERATED by tools/gen_icons.py from res/drawable/ic_*.xml. Do not edit by hand.")
lines.append("// Every icon is one filled path on a 24x24 viewport (the Android vector drawables).")
lines.append("")
lines.append("export global IconPaths {")
lines.append("    /// SVG path data of the icon called `name` (\"\" for an unknown name).")
lines.append("    pure public function d(name: string) -> string {")
expr = ""
for n, d, _ in icons:
    expr += f'        name == "{n}" ? "{d}" :\n'
expr += '        ""'
lines.append(expr + ";")
lines.append("    }")
lines.append("")
lines.append("    /// True for the icons whose drawable says fillType=\"evenOdd\".")
lines.append("    pure public function even-odd(name: string) -> bool {")
evens = [n for n, _, e in icons if e]
cond = " ||\n".join(f'        name == "{n}"' for n in evens)
lines.append(cond + ";")
lines.append("    }")
lines.append("}")
lines.append("")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"{len(icons)} icons, {len(evens)} even-odd -> {OUT}")
print("names:", " ".join(n for n, _, _ in icons))
